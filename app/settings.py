def map_area(key):
    """[south, west, north, east] of the area a map opens on (Settings > Map Areas), or None when the setting is empty or not four numbers."""
    try:
        v = [float(x) for x in (cfg(key) or "").split(",")]
    except ValueError:
        return None
    return v if len(v) == 4 and v[0] < v[2] and v[1] < v[3] else None


for _k in FEATURE_KEYS:   # who can see each feature (app/features.py): everyone until an administrator limits it
    DEFAULTS.setdefault("access_" + _k, "everyone")


def cfg_raw(key):
    """A setting as saved, whoever is asking (see cfg)."""
    return get_setting(key, DEFAULTS[key])


def cfg(key):
    """A setting with its built-in default when it has never been saved. A feature's own on-or-off switch answers "0" to a visitor the feature is hidden from (Settings > Site > Feature Access, app/access.py), so
    every menu, page and route that asks whether the feature is on hides it for that visitor too. Work with no signed-in person behind it (uploads to a private address, API keys, background jobs) uses the saved value."""
    v = get_setting(key, DEFAULTS[key])
    if v == "1" and key in ENABLE_KEYS and has_request_context() and not g.get("_cfg_raw"):
        from . import access
        if not access.allowed(ENABLE_KEYS[key]):
            return "0"
    return v


def cfg_float(key):
    try:
        return float(cfg(key))
    except ValueError:
        return float(DEFAULTS[key])


def cfg_int(key):
    try:
        return int(cfg(key))
    except ValueError:
        return int(DEFAULTS[key])


def _all():
    """Every setting in one query, kept for the rest of the request (a page asks for dozens)."""
    cache = g.get("_settings") if has_app_context() else None
    if cache is None:
        cache = {r["key"]: r["value"] for r in get_db().execute("SELECT key, value FROM settings").fetchall()}
        if has_app_context():
            g._settings = cache
    return cache


def get_setting(key, default=""):
    return _all().get(key, default)


def set_setting(key, value):
    d = get_db()
    d.execute("INSERT INTO settings (key, value) VALUES (%s,%s) "
              "ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value", (key, value))
    d.commit()
    if has_app_context() and g.get("_settings") is not None:
        g._settings[key] = value


def _fernet():
    digest = hashlib.sha256(current_app.config["SECRET_KEY"].encode()).digest()
    return Fernet(base64.urlsafe_b64encode(digest))


def get_secret(key):
    """Decrypted value, or empty if unset or the SECRET_KEY has changed since it was saved."""
    raw = get_setting(key)
    if not raw:
        return ""
    try:
        return _fernet().decrypt(raw.encode()).decode()
    except InvalidToken:
        return ""


def set_secret(key, value):
    set_setting(key, _fernet().encrypt(value.encode()).decode() if value else "")


def has_secret(key):
    return bool(get_setting(key))
